# Install Inno Setup 6 under Wine, the fallback packer: with
# ULRMM_WIN_PACKER=inno build_agents.sh builds the Windows installer with ISCC
# from build/setup.iss instead of makensis. Nothing runs this script
# automatically.
# Debian 12 on x86_64 (wine32). Needs sudo (only for apt), the Wine prefix
# belongs to the caller.
# Idempotent - a second run installs nothing more.
set -euo pipefail

PREFIX=${WINEPREFIX:-${ULRMM_AGENT_ROOT:-/opt/ulrmm-agents}/wine}
# Pinned version 6.4.3, runs as a 32-bit compiler under wine32.
# jrsoftware.org/download.php/is.exe now returns an HTML page, the files
# are on the GitHub releases.
INNO_VER=${INNO_VER:-6.4.3}
INNO_URL=${INNO_URL:-https://github.com/jrsoftware/issrc/releases/download/is-${INNO_VER//./_}/innosetup-${INNO_VER}.exe}
INNO_SHA256=${INNO_SHA256:-f3c42116542c4cc57263c5ba6c4feabfc49fe771f2f98a79d2f7628b8762723b}
# win32 prefix: "Program Files"; win64 prefix: "Program Files (x86)"
iscc_exe() {
  local d
  for d in "$PREFIX/drive_c/Program Files (x86)" "$PREFIX/drive_c/Program Files"; do
    [ -f "$d/Inno Setup 6/ISCC.exe" ] && { printf '%s' "$d/Inno Setup 6/ISCC.exe"; return 0; }
  done
  return 1
}

die() { echo "ERROR: $*" >&2; exit 1; }
[ "$(id -u)" -ne 0 ] || die "do not run as root - the Wine prefix must belong to the build user"
[ "$(uname -m)" = x86_64 ] || die "Inno Setup needs wine32, which exists only on x86_64"

echo "=== 1. Wine ==="
if command -v wine >/dev/null 2>&1; then
  echo "  present: $(wine --version)"
else
  echo "  installing: wine wine32 wine64 winbind (+ i386 architecture)"
  sudo dpkg --add-architecture i386
  sudo apt-get update -qq
  sudo DEBIAN_FRONTEND=noninteractive apt-get install -y --no-install-recommends \
    wine wine32:i386 wine64 winbind ca-certificates curl
  echo "  installed: $(wine --version)"
fi
# The Inno Setup installer opens a window even with /VERYSILENT and dies
# without an X server ("no driver could be loaded"). A virtual one is enough;
# xvfb-run needs xauth, the xvfb package does not pull it in.
if command -v xvfb-run >/dev/null 2>&1 && command -v xauth >/dev/null 2>&1; then
  echo "  xvfb and xauth present"
else
  echo "  installing: xvfb xauth"
  sudo DEBIAN_FRONTEND=noninteractive apt-get install -y --no-install-recommends xvfb xauth
fi

export WINEPREFIX="$PREFIX"
export WINEARCH=win32
export WINEDEBUG=-all

echo "=== 2. Wine prefix $PREFIX ==="
if [ -d "$PREFIX/drive_c" ]; then
  echo "  present"
else
  echo "  creating (win32)"
  mkdir -p "$PREFIX"
  wineboot -u >/dev/null 2>&1 || die "wineboot failed"
fi

echo "=== 3. Inno Setup $INNO_VER ==="
if ISCC_EXE=$(iscc_exe); then
  echo "  present: $ISCC_EXE"
else
  tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
  echo "  downloading $INNO_URL"
  curl -fsSL --max-time 900 -o "$tmp/inno.exe" "$INNO_URL" || die "download failed"
  # This file gets executed under Wine: first check that it is the pinned EXE
  # and not an error page with HTTP 200.
  [ "$(head -c 2 "$tmp/inno.exe")" = "MZ" ] || die "download is not a Windows executable"
  echo "$INNO_SHA256  $tmp/inno.exe" | sha256sum -c - >/dev/null || die "sha256 mismatch for the Inno Setup installer"
  echo "  silent install into $PREFIX"
  rc=0
  xvfb-run -a wine "$tmp/inno.exe" /VERYSILENT /SUPPRESSMSGBOXES /NORESTART /SP- >"$tmp/install.log" 2>&1 || rc=$?
  ISCC_EXE=$(iscc_exe) || { tail -5 "$tmp/install.log" >&2; die "ISCC.exe not found after the installation (wine exit $rc)"; }
  rm -rf "$tmp"; trap - EXIT
  echo "  installed: $ISCC_EXE"
fi

echo "=== 4. /usr/local/bin/iscc ==="
sudo tee /usr/local/bin/iscc >/dev/null <<EOF
#!/bin/sh
# Generated by riddix/agents/install-innosetup.sh. Runs under a virtual
# X server because Wine cannot create windows without a display.
WINEPREFIX="$PREFIX" WINEARCH=win32 WINEDEBUG=-all exec xvfb-run -a wine "$ISCC_EXE" "\$@"
EOF
sudo chmod 0755 /usr/local/bin/iscc
echo "  written"

echo "=== Test ==="
# ISCC /? exits with 1, so do not chain it into the pipeline directly
usage=$(iscc /? 2>&1 || true)
printf '%s\n' "$usage" | grep -im1 "Inno Setup" || die "iscc does not run"
echo "  ok - with ULRMM_WIN_PACKER=inno build_agents.sh finds iscc on the PATH"
