"""Writes the branding values of this instance into a ulrmm-agent source tree.

    write_brand.py <agent-src>        # needs the venv of the instance + Django
    write_brand.py --selftest         # no Django, checks ICO wrapper + Go escaping

Produces:
    <src>/agent/brand.go    Go vars: display texts, endpoints, identity
    <src>/build/brand.env   shell-sourceable, the ISCC /D defines
    <src>/build/brand.ico   only when favicon/logo is a PNG <= 256x256

Identity (service, paths, registry, Inno AppId) comes from the AGENT_* settings.
Different values are a different product: existing agents do not update into
them, they have to be migrated once.
"""

import base64
import json
import os
import re
import sys

DEFAULTS = {
    "BrandProductName": "UniversalLocal RMM",
    "BrandAgentName": "UniversalLocal RMM Agent",
    "BrandServiceDisplay": "UniversalLocal RMM Agent Service",
    "BrandPublisher": "UniversalLocal RMM",
}

BRAND_GO = '''// SPDX-FileCopyrightText: 2026 RiDDiX / Maximilian Hammerschmid
// SPDX-License-Identifier: FSL-1.1-ALv2

package agent

// Generated by riddix/agents/write_brand.py - do not edit by hand.
var (
\tBrandProductName    = {BrandProductName}
\tBrandAgentName      = {BrandAgentName}
\tBrandServiceDisplay = {BrandServiceDisplay}
\tBrandPublisher      = {BrandPublisher}

\t// pubip and python download, compiled in so the agent does not call out.
\tBrandPubIPURL = {BrandPubIPURL}
\tBrandPyURL    = {BrandPyURL}

\t// Ed25519 public key (base64) of the enrollment tokens, empty: none.
\tBrandEnrollPubKey = {BrandEnrollPubKey}

\t// Install names from the server AGENT_* settings. Different values are
\t// another product; existing installs do not update into them.
\tIdentWinSvcName    = {IdentWinSvcName}
\tIdentWinExe        = {IdentWinExe}
\tIdentWinProgDir    = {IdentWinProgDir}
\tIdentWinRegKey     = {IdentWinRegKey}
\tIdentNixBin        = {IdentNixBin}
\tIdentNixDir        = {IdentNixDir}
\tIdentNixConf       = {IdentNixConf}
\tIdentNixSvc        = {IdentNixSvc}
\tIdentMacPlistLabel = {IdentMacPlistLabel}
\tIdentTaskPrefix    = {IdentTaskPrefix}
\tIdentArtifact      = {IdentArtifact}
)
'''

def ident_go(ident: dict, task_prefix: str) -> dict:
    """agent_ident() keys -> Ident* variables for brand.go."""
    return {
        "IdentWinSvcName": ident["identSvcName"],
        "IdentWinExe": ident["identWinExe"],
        "IdentWinProgDir": ident["identWinProgDir"],
        "IdentWinRegKey": ident["identWinRegKey"],
        "IdentNixBin": ident["identNixBin"],
        "IdentNixDir": ident["identNixDir"],
        "IdentNixConf": ident["identNixConf"],
        "IdentNixSvc": ident["identNixSvc"],
        "IdentMacPlistLabel": ident["identMacPlistLabel"],
        "IdentTaskPrefix": task_prefix,
        "IdentArtifact": ident["identArtifact"],
    }


_CTRL = re.compile(r"[\x00-\x1f\x7f]")
# Inno doubles the leading brace: "{{GUID}". With a single brace Inno reads
# "{GUID}" as a constant and only fails during the ISCC run.
_APPID = re.compile(r"^\{\{[0-9A-Fa-f]{8}(-[0-9A-Fa-f]{4}){3}-[0-9A-Fa-f]{12}\}$")


def clean(value: str, fallback: str = "") -> str:
    """Strip control characters, normalize whitespace, empty -> fallback."""
    if not value:
        return fallback
    value = " ".join(_CTRL.sub(" ", str(value)).split())
    return value or fallback


def go_str(value: str) -> str:
    """Go string literal. json.dumps produces the escapes Go knows.

    ensure_ascii=False. Otherwise json writes surrogate pairs for emoji
    (\\ud83d\\ude80) and Go rejects them. Go source is UTF-8.
    """
    return json.dumps(clean(value), ensure_ascii=False)


def iss_str(value: str) -> str:
    """For Inno. Quotes break /D and Pascal, curly braces are Inno
    constants, percent is an escape in [Run] messages
    ("Acme 100% IT" is enough).
    """
    out = clean(value)
    for ch in ('"', "'", "{", "}", "%"):
        out = out.replace(ch, "")
    return out


def iss_appid(value: str) -> str:
    """Not through iss_str: that would delete the braces, and without them
    Inno installs next to the old copy instead of updating it. Check only.
    """
    out = clean(value)
    if not _APPID.match(out):
        raise ValueError(f"'{out}' is not an Inno AppId")
    return out


def png_to_ico(png: bytes) -> bytes:
    """PNG in an ICO container. Vista+ accepts PNG inside ICO, so only
    a 22 byte header in front. One size. No Pillow needed.
    """
    if png[:8] != b"\x89PNG\r\n\x1a\n" or png[12:16] != b"IHDR":
        raise ValueError("not a PNG")
    width = int.from_bytes(png[16:20], "big")
    height = int.from_bytes(png[20:24], "big")
    if not (0 < width <= 256 and 0 < height <= 256):
        raise ValueError("PNG larger than 256x256")
    header = b"\x00\x00\x01\x00\x01\x00"  # reserved, type=icon, count=1
    entry = bytes(
        [width & 0xFF, height & 0xFF, 0, 0]  # 256 -> byte 0
    ) + (1).to_bytes(2, "little") + (32).to_bytes(2, "little")
    entry += len(png).to_bytes(4, "little") + (22).to_bytes(4, "little")
    return header + entry + png


def data_uri_png(value: str) -> bytes:
    """PNG bytes from a data:image/png;base64,... URI, otherwise b""."""
    if not value:
        return b""
    prefix, _, payload = str(value).partition(",")
    if not payload or not prefix.lower().startswith("data:image/png"):
        return b""
    try:
        return base64.b64decode(payload, validate=True)
    except Exception:
        return b""


def brand_values(product_name: str, company_name: str) -> dict:
    product = clean(product_name, DEFAULTS["BrandProductName"])
    if product == DEFAULTS["BrandProductName"]:
        return dict(DEFAULTS)
    agent = f"{product} Agent"
    return {
        "BrandProductName": product,
        "BrandAgentName": agent,
        # must match setup.iss: sc config ... "{#MyAppName} Service"
        "BrandServiceDisplay": f"{agent} Service",
        "BrandPublisher": clean(company_name, DEFAULTS["BrandPublisher"]),
    }


def enroll_pubkey() -> str:
    """Public key for ENROLL_SIGNING_KEY, empty without a (valid) key.
    build_agents.sh stores it as enroll-pubkey.txt next to the artifacts."""
    from django.core.exceptions import ImproperlyConfigured

    from deploy.signing import public_key_b64

    try:
        return public_key_b64()
    except ImproperlyConfigured as e:
        print(f"  enrollment key: none ({e})")
        return ""


def py_zip_url(configured: str, dist_url: str) -> str:
    """Python URL of the Windows agents: ULRMM_AGENT_PY_URL, otherwise the
    mirror under <agentdist>/python (build_agents.sh)."""
    return clean(configured) or clean(dist_url).rstrip("/") + "/python"


def write(
    src: str,
    product_name: str,
    company_name: str,
    support_url: str,
    icon: bytes,
    ident: dict,
    app_id: str,
    pubip_url: str = "",
    py_url: str = "",
    enroll_key: str = "",
) -> None:
    vals = brand_values(product_name, company_name)
    app_id = iss_appid(app_id)

    endpoints = {
        "BrandPubIPURL": clean(pubip_url),
        "BrandPyURL": clean(py_url),
        "BrandEnrollPubKey": clean(enroll_key),
    }

    go_path = os.path.join(src, "agent", "brand.go")
    with open(go_path, "w", encoding="utf-8") as fh:
        fh.write(
            BRAND_GO.format(
                **{
                    k: go_str(v)
                    for k, v in {**vals, **endpoints, **ident}.items()
                }
            )
        )
    print(f"  {go_path}: {vals['BrandProductName']} / {vals['BrandPublisher']}")
    print(
        f"  identity: {ident['IdentWinSvcName']}"
        f" / {ident['IdentArtifact']} / {app_id}"
    )

    url = iss_str(support_url)
    env_path = os.path.join(src, "build", "brand.env")
    with open(env_path, "w", encoding="utf-8") as fh:
        fh.write(
            "# Generated by write_brand.py - source this, then pass as ISCC /D flags.\n"
            f"ISCC_APP_NAME='{iss_str(vals['BrandAgentName'])}'\n"
            f"ISCC_PUBLISHER='{iss_str(vals['BrandPublisher'])}'\n"
            f"ISCC_URL='{url}'\n"
            f"ISCC_APP_ID='{app_id}'\n"
            f"ISCC_EXE_NAME='{iss_str(ident['IdentWinExe'])}'\n"
            f"ISCC_SVC_NAME='{iss_str(ident['IdentWinSvcName'])}'\n"
            f"ISCC_PROG_DIR='{iss_str(ident['IdentWinProgDir'])}'\n"
            f"ISCC_REG_KEY='{iss_str(ident['IdentWinRegKey'])}'\n"
        )
    print(f"  {env_path}")

    ico_path = os.path.join(src, "build", "brand.ico")
    if icon:
        try:
            with open(ico_path, "wb") as fh:
                fh.write(png_to_ico(icon))
            print(f"  {ico_path}: {len(icon)} byte PNG")
            return
        except ValueError as e:
            print(f"  brand.ico skipped: {e}")
    if os.path.exists(ico_path):
        os.remove(ico_path)


def main(src: str) -> int:
    if not os.path.isdir(os.path.join(src, "agent")):
        print(f"not a ulrmm-agent tree: {src}", file=sys.stderr)
        return 1

    sys.path.insert(0, os.environ.get("ULRMM_API_DIR", "/rmm/api/ulrmm"))
    os.environ.setdefault("DJANGO_SETTINGS_MODULE", "ulrmm.settings")
    import django

    django.setup()
    from django.conf import settings

    from agents.utils import get_agents_dist_url
    from core.utils import get_branding
    from ulrmm.agent_ident import agent_ident, agent_task_prefix

    b = get_branding()
    write(
        src,
        b.product_name,
        b.company_name or "",
        b.support_url or "",
        data_uri_png(b.favicon) or data_uri_png(b.logo),
        ident_go(agent_ident(), agent_task_prefix()),
        settings.AGENT_INNO_APPID,
        pubip_url=getattr(settings, "ULRMM_AGENT_PUBIP_URL", "") or "",
        py_url=py_zip_url(
            getattr(settings, "ULRMM_AGENT_PY_URL", "") or "", get_agents_dist_url()
        ),
        enroll_key=enroll_pubkey(),
    )
    return 0


def demo() -> None:
    # 1x1 PNG
    png = base64.b64decode(
        "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNk"
        "YPhfDwAChwGA60e6kgAAAABJRU5ErkJggg=="
    )
    ico = png_to_ico(png)
    assert ico[:6] == b"\x00\x00\x01\x00\x01\x00", ico[:6]
    assert ico[6] == 1 and ico[7] == 1, "1x1 in the directory entry"
    assert int.from_bytes(ico[14:18], "little") == len(png)
    assert int.from_bytes(ico[18:22], "little") == 22
    assert ico[22:] == png, "PNG appended unchanged"

    # 256 edge: width/height 256 have to end up as byte 0
    big = bytearray(png)
    big[16:24] = (256).to_bytes(4, "big") + (256).to_bytes(4, "big")
    assert png_to_ico(bytes(big))[6:8] == b"\x00\x00"
    big[16:24] = (257).to_bytes(4, "big") + (256).to_bytes(4, "big")
    try:
        png_to_ico(bytes(big))
        raise AssertionError("257px should have been rejected")
    except ValueError:
        pass
    try:
        png_to_ico(b"GIF89a....")
        raise AssertionError("non-PNG should have been rejected")
    except ValueError:
        pass
    assert data_uri_png("data:image/svg+xml;base64,AAAA") == b""
    assert data_uri_png("data:image/png;base64,!!!not-base64") == b""

    # Go escaping: the result has to be a valid Go literal
    assert go_str('Ac"me\\Inc') == '"Ac\\"me\\\\Inc"'
    assert go_str("a\nb\tc") == '"a b c"', go_str("a\nb\tc")
    # UTF-8 stays UTF-8: ASCII escaping would write surrogate pairs for
    # emoji, which Go does not translate ("invalid Unicode code point")
    assert go_str("Grüße") == '"Grüße"'
    assert go_str("🚀 RMM") == '"🚀 RMM"'
    assert "\\ud" not in go_str("🚀 RMM")
    assert go_str("") == '""'
    assert "\n" not in go_str("x\x00\x1by")

    # Inno: no quotes, no braces, no percent
    assert iss_str('A"B\'C{D}') == "ABCD"
    assert iss_str("Acme 100% IT") == "Acme 100 IT"

    # AppId: check only. iss_str would delete exactly those braces
    app_id = "{{61D095D9-C6CE-4D60-B192-4C6699822C40}"
    assert iss_appid(app_id) == app_id
    assert iss_appid(" {{61d095d9-c6ce-4d60-b192-4c6699822c40} ").startswith("{{6")
    for bad in (
        "",
        "61D095D9-C6CE-4D60-B192-4C6699822C40",
        iss_str(app_id),
        # one brace: a constant for Inno, not an AppId
        "{61D095D9-C6CE-4D60-B192-4C6699822C40}",
        "{{61D095D9-C6CE-4D60-B192-4C6699822C4}",
        "{{not-a-guid}",
    ):
        try:
            iss_appid(bad)
            raise AssertionError(f"AppId '{bad}' should have been rejected")
        except ValueError:
            pass

    # Identity: agent_ident() keys -> Ident* variables, complete
    ident = ident_go(
        {
            "identSvcName": "ulrmm-agent",
            "identWinExe": "ulrmm-agent.exe",
            "identWinProgDir": "ULRMM Agent",
            "identWinProgPath": "C:\\Program Files\\ULRMM Agent",
            "identWinRegKey": "UniversalLocalRMM",
            "identWinProgData": "C:\\ProgramData\\UniversalLocalRMM",
            "identNixBin": "ulrmm-agent",
            "identNixDir": "/opt/ulrmm-agent",
            "identNixConf": "/etc/ulrmm-agent",
            "identNixSvc": "ulrmm-agent.service",
            "identMacPlistLabel": "ulrmm-agent",
            "identArtifact": "ulrmm-agent",
        },
        "ULRMM_",
    )
    assert set(ident) == set(re.findall(r"\{(Ident\w+)\}", BRAND_GO)), ident
    assert ident["IdentWinSvcName"] == "ulrmm-agent"
    assert ident["IdentTaskPrefix"] == "ULRMM_"

    # Fallbacks
    assert brand_values("", "") == DEFAULTS
    assert brand_values("UniversalLocal RMM", "Foo") == DEFAULTS
    v = brand_values("  Riddix  RMM ", "")
    assert v["BrandProductName"] == "Riddix RMM"
    assert v["BrandAgentName"] == "Riddix RMM Agent"
    assert v["BrandServiceDisplay"] == "Riddix RMM Agent Service"
    assert v["BrandPublisher"] == DEFAULTS["BrandPublisher"]

    # Python URL: the setting, otherwise the mirror under <agentdist>/python
    dist = "https://api.example.com/agentdist"
    assert py_zip_url("", dist) == dist + "/python"
    assert py_zip_url("", dist + "/") == dist + "/python"
    own = "https://py.example.com/zips"
    assert py_zip_url(f" {own} ", dist) == own

    # brand.go has to be fillable at all times
    key = "ZmFrZS1lZDI1NTE5LXB1YmxpYy1rZXktMzItYnl0ZXM="
    full = {
        **v,
        "BrandPubIPURL": "https://api.example.com/pubip",
        "BrandPyURL": py_zip_url("", dist),
        "BrandEnrollPubKey": key,
        **ident,
    }
    assert set(full) == set(re.findall(r"\{(\w+)\}", BRAND_GO)), full
    src = BRAND_GO.format(**{k: go_str(x) for k, x in full.items()})
    # base64 stays as is, build_agents.sh reads the value back with sed
    assert f'BrandEnrollPubKey = "{key}"' in src, src
    full["BrandEnrollPubKey"] = ""
    assert 'BrandEnrollPubKey = ""' in BRAND_GO.format(
        **{k: go_str(x) for k, x in full.items()}
    )
    assert 'BrandAgentName      = "Riddix RMM Agent"' in src, src
    assert 'BrandPubIPURL = "https://api.example.com/pubip"' in src, src
    assert 'BrandPyURL    = "https://api.example.com/agentdist/python"' in src, src
    assert 'IdentNixSvc        = "ulrmm-agent.service"' in src, src
    assert 'IdentTaskPrefix    = "ULRMM_"' in src, src
    assert "{" not in src.split("var (", 1)[1], "placeholder left over"
    print("selftest ok")


if __name__ == "__main__":
    args = sys.argv[1:]
    if args[:1] == ["--selftest"]:
        demo()
    elif len(args) == 1:
        sys.exit(main(args[0]))
    else:
        print(__doc__, file=sys.stderr)
        sys.exit(2)
